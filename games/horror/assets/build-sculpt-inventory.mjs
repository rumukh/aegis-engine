import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';

const options = new Map(),
  args = process.argv.slice(2);
for (let i = 0; i < args.length; i += 2) {
  assert.ok(
    ['--previous', '--assembly', '--closure', '--out'].includes(args[i]) &&
      args[i + 1] &&
      !options.has(args[i]),
  );
  options.set(args[i], resolve(args[i + 1]));
}
for (const key of ['--previous', '--assembly', '--closure', '--out']) assert.ok(options.has(key));
const previous = JSON.parse(await readFile(options.get('--previous'), 'utf8'));
const assembly = JSON.parse(await readFile(options.get('--assembly'), 'utf8'));
const closure = JSON.parse(await readFile(options.get('--closure'), 'utf8'));
assert.ok(!closure.status.startsWith('STOP'));
assert.equal(closure.candidate.baseVisualBytes, 49252392);
assert.equal(closure.candidate.visualBytes, 51241160);
assert.equal(closure.candidate.totalBytes, 52746947);
const endingPaths = new Set(closure.finalEnding.models.map((model) => model.path));
const files = closure.visualClosure
  .filter((file) => !endingPaths.has(file.path))
  .map(({ path, bytes, sha256 }) => {
    assert.ok(path.startsWith('generated/') && !path.slice('generated/'.length).includes('/'));
    return { file: path.slice('generated/'.length), bytes, sha256 };
  });
assert.equal(files.length, 42);
assert.equal(
  files.reduce((sum, file) => sum + file.bytes, 0),
  closure.candidate.baseVisualBytes,
);
const body = await readFile(join(dirname(options.get('--assembly')), 'responder.glb'));
const doc = JSON.parse(body.toString('utf8', 20, 20 + body.readUInt32LE(12)));
const oldBody = previous.models.find((model) => model.file === 'responder.glb');
const newBody = {
  ...oldBody,
  bytes: body.length,
  triangles: assembly.triangles,
  primitives: doc.meshes.reduce((sum, mesh) => sum + mesh.primitives.length, 0),
  materials: doc.materials.map((material) => material.name),
  dependencies: doc.images.map((image) => image.uri),
  bounds: assembly.bounds,
};
assert.equal(
  createHash('sha256').update(body).digest('hex'),
  files.find((file) => file.file === 'responder.glb').sha256,
);
const textures = previous.textures.filter(
  (texture) => !['colony-shell-basecolor.png', 'colony-shell-orm.png'].includes(texture.file),
);
for (const file of ['insert-basecolor.jpg', 'insert-normal.png', 'insert-orm.png']) {
  const entry = files.find((entry) => entry.file === file);
  assert.ok(entry);
  textures.push({
    file,
    width: 2048,
    height: 2048,
    bytes: entry.bytes,
    recipe: file.endsWith('.jpg')
      ? 'Existing Blender3.2.2 scripted high-poly source baked to lossless sRGB PNG;2K runtimeJPEG encoded without colorgrade; rawPNG/source.blend retained.'
      : 'Existing Blender3.2.2 selected-to-active high/low bake,2K lossless non-color tangentnormal orpacked AO/roughness/nonmetal. No external/generated imagery.',
  });
}
const result = {
  ...previous,
  revision: 'sculpt-insert-game-review-1',
  status:
    'Parent approved neutral/isolated-torch checkpoint for boundedGAMEreview; matched actualtorch/human direction approval pending',
  files,
  models: previous.models.map((model) => (model.file === 'responder.glb' ? newBody : model)),
  textures,
  budget: {
    ...previous.budget,
    totalBytes: closure.candidate.baseVisualBytes,
    decodedUniqueTextureBytesWithMipmaps: Math.ceil(
      textures.reduce((sum, image) => sum + (image.width * image.height * 4 * 4) / 3, 0),
    ),
    reservationScope:
      'Existing BASEart48MiB+16MiB guard unchanged. Parent separately allocated combinedvisualsINCLUDINGuser-ending50MiB+14MiBaudio; see combinedBudgetDecision.',
  },
  combinedBudgetDecision: { ...closure.allocationDecision, measured: closure.candidate },
  sculptWorkflow: {
    source: 'source/sculpt-insert/sculpt-provenance.json',
    highPoly: 'source/sculpt-insert/infestation-sculpt.blend',
    originalLosslessBakes: 'source/sculpt-insert/',
    authorScript: 'source/sculpt_infestation.py',
    colorCook: 'source/cook_sculpt_basecolor.py',
    retainedBodyInput: 'source/sculpt-input/responder.glb',
    retainedBodyInventory: 'source/sculpt-input/inventory.json',
    assembler: 'assemble-sculpt.mjs',
    assemblyProof: 'generated/sculpt-provenance.json',
    note: 'The former procedural prototype sources remain historical rejected lineage; final responder is assembled from the retained Blender export, not generated by the rejected procedural infestation functions.',
  },
  orphanPruning: {
    files: closure.prunedOrphans.map((file) => ({
      file: file.path.slice('generated/'.length),
      bytes: file.bytes,
      sha256: file.sha256,
    })),
    runtimeBytesSaved: closure.runtimeBytesSavedByPruning,
    beforeAppearanceInputSha256: closure.preservation.beforeAppearanceDefinitionSha256,
    afterAppearanceInputSha256: closure.preservation.afterAppearanceDefinitionSha256,
    note: 'Only unreferenced rejected base/ORM images were pruned;colony normal retained bystruggle. No actual render dependency,acceptedtextureoroptics changed.',
  },
  recipe: {
    revision: 'sculpt-insert-game-review-1',
    status:
      'Parent-approved asset-only sculpt checkpoint; actual matched-game/human character approval pending',
    activeResponder: 'source/sculpt-insert/sculpt-provenance.json',
    assembly: 'assemble-sculpt.mjs',
    retainedRejectedBody: 'source/sculpt-input/responder.glb',
    unchangedStruggleRecipe: 'source/horror-pass.recipe.json',
    reality:
      'Existing Blender3.2.2 scripted continuous-volume sculpt, targeted cloth and insert-only decimation; 2Kselected-to-active bakes. Not hand sculpting, hand retopology, AI model generation or full-game artistic acceptance.',
    previousProceduralRecipe: previous.recipe,
  },
};
await writeFile(options.get('--out'), `${JSON.stringify(result, null, 2)}\n`, { flag: 'wx' });
process.stdout.write(
  `${JSON.stringify({ output: options.get('--out'), files: files.length, baseVisualBytes: result.budget.totalBytes, combinedVisualBytes: closure.candidate.visualBytes, combinedBytes: closure.candidate.totalBytes }, null, 2)}\n`,
);
